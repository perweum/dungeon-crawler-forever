#!/usr/bin/env python3
"""Print a Markdown checklist (stdout) for checking our boss abilities by hand against Wowhead Classic. Read-only, offline.

Per released dungeon (data/manual/dungeon_status.csv hidden/classic rows are skipped) and boss: the NPC ID(s) from AtlasLoot (matched
like tools/gen_abilities.py does), a https://www.wowhead.com/classic/npc=<id> link for a person to open, and our spells as "id name".
Bosses with an NPC ID that have no spells in Data/Abilities.lua, or lost spell names since --base (default 31af694, the last main before
the abilities refresh; names our current filter drops do not count as lost), come first, marked "check first".
This tool only builds link strings; it never fetches Wowhead or any other site (ZAM's terms forbid tools/agents).
Needs data/raw/<build>/SpellName.csv (git-ignored) and the installed AtlasLoot Forever (WOW_DIR, or the folder as argument).
Usage: tools/abilities_checklist.py [--base REV] [path/to/AtlasLootClassic_DungeonsAndRaids] > checklist.md
"""
import csv, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BASE = "31af694"
args = sys.argv[1:]
if args[:1] == ["--base"]:
    BASE, args = args[1], args[2:]
elif args[:1] and args[0].startswith("-"):
    sys.exit(__doc__)
sys.argv = [sys.argv[0]] + args[:1]  # gen_loot reads the AtlasLoot folder from argv[1]
sys.path.insert(0, HERE)
import gen_loot  # noqa: E402
import gen_abilities as ga  # noqa: E402

ABILITIES = "addon/DungeonCrawlerForever/Data/Abilities.lua"
WOWHEAD = "https://www.wowhead.com/classic/npc=%d"

def parse_abilities(text):
    """{(instanceMapID, boss): [spellID, ...]} from a generated Abilities.lua."""
    out, inst = {}, None
    for line in text.splitlines():
        m = re.match(r"  \[(\d+)\] = \{", line)
        if m:
            inst = int(m.group(1)); continue
        m = re.match(r'    \["((?:[^"\\]|\\.)*)"\] = \{([\d,]*)\},', line)
        if m:
            out[(inst, m.group(1).replace('\\"', '"'))] = [int(x) for x in m.group(2).split(",") if x]
    return out

def hidden_instances():
    with open(os.path.join(ROOT, "data/manual/dungeon_status.csv"), encoding="utf-8") as f:
        return {int(r["instanceMapID"]) for r in csv.DictReader(f) if r["status"].strip() in ("hidden", "classic")}

def main():
    names = ga.forever_spell_names()
    spell = lambda sp: f"{sp} {names.get(sp, '(not in this build)')}"
    new = parse_abilities(open(os.path.join(ROOT, ABILITIES), encoding="utf-8").read())
    git = subprocess.run(["git", "show", f"{BASE}:{ABILITIES}"], capture_output=True, text=True, cwd=ROOT)
    if git.returncode:
        sys.exit(f"git show {BASE}:{ABILITIES} failed: {git.stderr.strip()}")
    old = parse_abilities(git.stdout)
    atlas, ours, hidden = gen_loot.parse_atlas(), gen_loot.our_bosses(), hidden_instances()
    first, rest, no_npc = [], [], []
    for inst in sorted(ours):
        if inst in hidden:
            continue
        dname, bnames = ours[inst]
        by = ga.by_norm_name(atlas.get(inst, []))
        for boss in bnames:
            npcs = list(dict.fromkeys(ga.boss_npcs(by, boss)))
            ids = new.get((inst, boss), [])
            now = {names.get(sp, "").lower() for sp in ids}
            lost = [sp for sp in old.get((inst, boss), []) if names.get(sp, "").lower() not in now
                    and not (sp in names and ga.internal_name(names[sp]))]
            head = f"- [ ] **{boss}** — {dname} ({inst})"
            if npcs:
                head += " — " + ", ".join(f"NPC {n} {WOWHEAD % n}" for n in npcs)
            lines = [head]
            reasons = (["no spells in our data"] if not ids else []) + (["lost since " + BASE + ": " + ", ".join(map(spell, lost))] if lost else [])
            if reasons and npcs:
                lines[0] += " — **check first**"
            lines += [f"  - {r}" for r in reasons] + [f"  - {spell(sp)}" for sp in ids]
            (first if reasons and npcs else rest if npcs else no_npc).append(lines)
    print("# Boss abilities: Wowhead Classic checklist")
    print(f"Generated by tools/abilities_checklist.py from {ABILITIES} (build {open(os.path.join(ROOT, 'data/BUILD')).read().strip()}), "
          f"compared with {BASE}. Open the links yourself; nothing here was fetched. Tick a boss when its spells match Wowhead's Abilities tab.")
    for title, group in ((f"Check first ({len(first)} bosses: no spells, or spells lost since {BASE})", first),
                         (f"Everything else ({len(rest)} bosses)", rest),
                         (f"No AtlasLoot NPC ID ({len(no_npc)} bosses: Forever-new or unmatched, nothing to look up)", no_npc)):
        print(f"\n## {title}")
        for lines in group:
            print("\n".join(lines))

if __name__ == "__main__":
    main()
