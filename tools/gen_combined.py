#!/usr/bin/env python3
"""Generate addon/DungeonCrawlerForever/Data/Combined.lua from data/manual/combined_maps.csv.

A combined map is one big map made of pieces (cropped parts) of the dungeon's own floor art, laid out like the printed guides: no extra
image is shipped, only crop rectangles and positions. Rows: kind=canvas (dx, dy = canvas width, height), kind=bg (a crop that is
stretched over the canvas as parchment; must lie inside one 256 px tile), kind=piece (floor, crop x0,y0,x1,y1 in source art pixels,
destination dx,dy in canvas pixels, scale).
"""
import csv, os, re, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "addon/DungeonCrawlerForever/Data/Combined.lua")

def main():
    art = open(os.path.join(ROOT, "addon/DungeonCrawlerForever/Data/Art.lua"), encoding="utf-8").read()
    floors = set(re.findall(r"uiMapID = (\d+)", art))
    inst = collections.OrderedDict()
    for n, r in enumerate(csv.DictReader(open(os.path.join(ROOT, "data/manual/combined_maps.csv"), encoding="utf-8")), 2):
        c = inst.setdefault(r["instanceMapID"], {"pieces": []})
        k = r["kind"]
        if k == "canvas":
            c["w"], c["h"] = int(r["dx"]), int(r["dy"])
            continue
        if r["floorUiMapID"] not in floors:
            raise SystemExit(f"combined_maps.csv line {n}: floor {r['floorUiMapID']} has no client art")
        x0, y0, x1, y1 = (int(float(r[k_])) for k_ in ("x0", "y0", "x1", "y1"))
        if x1 <= x0 or y1 <= y0:
            raise SystemExit(f"combined_maps.csv line {n}: empty crop")
        if k == "bg":
            if x0 // 256 != (x1 - 1) // 256 or y0 // 256 != (y1 - 1) // 256:
                raise SystemExit(f"combined_maps.csv line {n}: the bg crop must lie inside one 256 px tile")
            c["bg"] = (int(r["floorUiMapID"]), x0, y0, x1, y1)
        else:
            c["pieces"].append((int(r["floorUiMapID"]), x0, y0, x1, y1, int(float(r["dx"])), int(float(r["dy"])), float(r["scale"] or 1)))
    lines = ["-- GENERATED by tools/gen_combined.py from data/manual/combined_maps.csv. Do not edit.",
             "-- [instanceMapID] = { w, h = canvas size, bg = crop stretched over the canvas, pieces = crops of the floor art placed on the canvas (source pixels -> canvas pixels) }",
             "local _, ns = ...", "ns.Combined = {"]
    for mid, c in inst.items():
        if "w" not in c or not c["pieces"]:
            raise SystemExit(f"instance {mid}: needs a canvas row and at least one piece")
        lines.append(f"  [{mid}] = {{ w = {c['w']}, h = {c['h']},")
        if "bg" in c:
            f, x0, y0, x1, y1 = c["bg"]
            lines.append(f"    bg = {{ floor = {f}, x0 = {x0}, y0 = {y0}, x1 = {x1}, y1 = {y1} }},")
        lines.append("    pieces = {")
        for f, x0, y0, x1, y1, dx, dy, s in c["pieces"]:
            lines.append(f"      {{ floor = {f}, x0 = {x0}, y0 = {y0}, x1 = {x1}, y1 = {y1}, dx = {dx}, dy = {dy}, s = {s:g} }},")
        lines.append("    },")
        lines.append("  },")
    lines.append("}")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {len(inst)} combined map(s)")

main()
