#!/usr/bin/env python3
"""Generate addon/DungeonCrawlerForever/Data/ArtCustom.lua from bundled map tiles in addon/DungeonCrawlerForever/Art/.

Tile file naming (BLP preferred, TGA works too; each tile 256x256 power-of-two):
    <instanceMapID>_<floor>_<row>_<col>.blp      floor, row, col are 1-based
e.g. 3065_1_1_1.blp ... 3065_1_4_6.blp for a 6x4 grid (1536x1024 map).
Credits/names come from data/manual/art_credits.csv: instanceMapID,floor,floorName,credit,url
The grid size is detected from the files present. Custom art takes precedence over the stitched/retail art.
"""
import csv, os, re, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "addon/DungeonCrawlerForever/Art")
TILE = 256
PATH = "Interface\\\\AddOns\\\\DungeonCrawlerForever\\\\Art\\\\"

def main():
    pat = re.compile(r"^(\d+)_(\d+)_(\d+)_(\d+)\.(blp|tga)$", re.I)
    maps = collections.defaultdict(dict)  # (inst, floor) -> {(row,col): filename-without-ext}
    for fn in sorted(os.listdir(ART)) if os.path.isdir(ART) else []:
        m = pat.match(fn)
        if m:
            inst, fl, r, c = (int(m.group(i)) for i in range(1, 5))
            maps[(inst, fl)][(r, c)] = os.path.splitext(fn)[0]
    credits = {}
    cp = os.path.join(ROOT, "data/manual/art_credits.csv")
    if os.path.exists(cp):
        for r in csv.DictReader(open(cp, encoding="utf-8")):
            credits[(int(r["instanceMapID"]), int(r.get("floor") or 1))] = r
    out = ["-- GENERATED by tools/gen_custom_art.py from addon/DungeonCrawlerForever/Art/*.blp. Do not edit.",
           "-- Bundled, credited community map art (see data/SOURCES.md). Same shape as Art.lua, tiles are addon file paths.",
           "local _, ns = ...", "ns.ArtCustom = {", ]
    credit_lines = ["ns.ArtCredits = {"]
    byinst = collections.defaultdict(list)
    for (inst, fl) in sorted(maps):
        grid = maps[(inst, fl)]
        rows = max(k[0] for k in grid)
        cols = max(k[1] for k in grid)
        missing = [(r, c) for r in range(1, rows + 1) for c in range(1, cols + 1) if (r, c) not in grid]
        if missing:
            print(f"WARNING {inst} floor {fl}: missing tiles {missing[:6]}{'...' if len(missing) > 6 else ''}")
        tiles = "{" + ",".join("{" + ",".join('"%s%s"' % (PATH, grid.get((r, c), "")) if (r, c) in grid else '""' for c in range(1, cols + 1)) + "}" for r in range(1, rows + 1)) + "}"
        cr = credits.get((inst, fl), {})
        name = cr.get("floorName") or ""
        nm = f', name = "{name}"' if name else ""
        byinst[inst].append(f'    {{ uiMapID = {800000 + inst * 10 + fl}{nm}, custom = true, w = {cols * TILE}, h = {rows * TILE}, tile = {TILE}, tiles = {tiles} }},')
        if cr.get("credit") and fl == 1:
            credit_lines.append(f'  [{inst}] = {{ text = "{cr["credit"]}", url = "{cr.get("url", "")}" }},')
        print(f"{inst} floor {fl}: {rows}x{cols} tiles ({cols * TILE}x{rows * TILE})")
    for inst, lines in byinst.items():
        out.append(f"  [{inst}] = {{ -- custom art")
        out.extend(lines)
        out.append("  },")
    out.append("}")
    credit_lines.append("}")
    out.extend(credit_lines)
    p = os.path.join(ROOT, "addon/DungeonCrawlerForever/Data/ArtCustom.lua")
    open(p, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote", p)

main()
