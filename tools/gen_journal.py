#!/usr/bin/env python3
"""Generate addon/DungeonCrawlerForever/Data/Journal.lua: per dungeon / raid, the loading screen image for its card in the journal page, and the addon
version that added it (for the "New" badge).

Source: Forever `Map.LoadingScreenID` -> `LoadingScreens` (data/raw/<build>/, fetched by tools/fetch_db2.sh).
  new dungeons  : MainImageFileDataID  (16:9 image with transparent bands above and below: kind "new")
  classic ones  : NarrowScreenFileDataID (a 2048x2048 texture with the WoW logo and a bronze frame: kind "classic")
Only FileDataIDs are written (the images are the game's own, shown by ID; nothing is bundled). The addon crops them (UI/Journal.lua, CROP) to the
painted band: checked on build 1.60.1.70862, all 26 classic images share one layout and all 9 new ones share another.
`added` comes from data/manual/dungeon_added.csv (instanceMapID,version,note). Run by tools/update.py after gen_dungeons.py.
"""
import csv, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = open(os.path.join(ROOT, "data/BUILD")).read().strip()
RAW = os.path.join(ROOT, "data/raw", BUILD)
DUNGEONS = os.path.join(ROOT, "addon/DungeonCrawlerForever/Data/Dungeons.lua")
OUT = os.path.join(ROOT, "addon/DungeonCrawlerForever/Data/Journal.lua")

def main():
    screens = {r["ID"]: r for r in csv.DictReader(open(os.path.join(RAW, "LoadingScreens.csv"), encoding="utf-8"))}
    maps = {r["ID"]: r for r in csv.DictReader(open(os.path.join(RAW, "Map.csv"), encoding="utf-8"))}
    added = {}
    ap = os.path.join(ROOT, "data/manual/dungeon_added.csv")
    if os.path.exists(ap):
        added = {r["instanceMapID"]: r["version"] for r in csv.DictReader(open(ap, encoding="utf-8"))}
    ids = [m.group(1) for m in re.finditer(r"^  \[(\d+)\] = \{ name = ", open(DUNGEONS, encoding="utf-8").read(), re.M)]
    out = ["-- GENERATED by tools/gen_journal.py. Do not edit.",
           "-- [instanceMapID] = { art = loading screen FileDataID, kind = \"new\" | \"classic\" (how UI/Journal.lua crops it), added = addon version that added the dungeon }",
           "local _, ns = ...", "ns.Journal = {"]
    n = missing = 0
    for inst in ids:
        m = maps.get(inst)
        s = screens.get(m["LoadingScreenID"]) if m else None
        art = kind = None
        if s and s["MainImageFileDataID"] not in ("", "0"):
            art, kind = s["MainImageFileDataID"], "new"
        elif s and s["NarrowScreenFileDataID"] not in ("", "0"):
            art, kind = s["NarrowScreenFileDataID"], "classic"
        fields = []
        if art:
            fields += [f"art = {art}", f'kind = "{kind}"']
            n += 1
        else:
            missing += 1
            print(f"no loading screen for instance {inst}")
        if inst in added:
            fields.append(f'added = "{added[inst]}"')
        if fields:
            out.append(f"  [{inst}] = {{ {', '.join(fields)} }},")
    out.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {OUT}: {n} loading screens, {missing} without")

main()
