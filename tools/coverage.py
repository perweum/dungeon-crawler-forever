#!/usr/bin/env python3
"""Write data/STATUS.md: per-dungeon data coverage (what is automated vs still needs a human). Run after any data change."""
import os, re, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "addon/DungeonCrawlerForever/Data")
rd = lambda n: open(os.path.join(D, n), encoding="utf-8").read()
build = open(os.path.join(ROOT, "data/BUILD")).read().strip()

def instances(text):
    return {int(m.group(1)): m.group(2) for m in re.finditer(r"^  \[(\d+)\] = \{ -- ([^\n]*)", text, re.M)}
retail, forever, custom = rd("Art.lua"), rd("ArtForever.lua"), rd("ArtCustom.lua")
art = {}
for kind, t in (("retail", retail), ("stitched", forever), ("community", custom)):
    for i in instances(t): art[i] = kind if i not in art or kind == "community" else art[i]
loot = rd("Loot.lua")
loot_names = collections.defaultdict(set)
cur = None
for line in loot.split("\n"):
    m = re.match(r"  \[(\d+)\] = \{", line)
    if m: cur = int(m.group(1))
    m = re.match(r'    \["([^"]+)"\] = ', line)
    if m and cur: loot_names[cur].add(m.group(1))
entr = {int(i) for i in re.findall(r"instance = (\d+)", rd("Entrances.lua"))}

rows = []
dun = rd("Dungeons.lua")
for m in re.finditer(r'\[(\d+)\] = \{ name = "([^"]+)", raid = (true|false)([^\n]*)bosses = \{\n((?:    \{[^\n]*\n)+)', dun):
    inst, name, raid, meta, body = int(m.group(1)), m.group(2), m.group(3) == "true", m.group(4), m.group(5)
    if raid: continue
    seen, pos, port, approx = {}, 0, 0, 0
    for b in re.finditer(r'name = "([^"]+)"[^\n]*', body):
        n, line = b.group(1), b.group(0)
        if n in seen: continue
        seen[n] = line
    for n, line in seen.items():
        pos += "x =" in line
        approx += "approx = true" in line
        port += ("portrait =" in line or "display =" in line)
    lv = re.search(r"recMin = (\d+), recMax = (\d+)", meta)
    rows.append((int(lv.group(1)) if lv else 999, name, inst, art.get(inst, "none"), len(seen), pos, approx, port, len([n for n in seen if n in loot_names.get(inst, ())]), inst in entr, lv.group(0).replace("recMin = ", "").replace(", recMax = ", "-") if lv else "?"))
rows.sort()
def pct(a, b): return f"{a}/{b}" + ("" if a == b else "")
lines = [f"# Data coverage (generated by tools/coverage.py, build {build})", "",
         "Dungeons only. Columns show how much of each dungeon is complete. **Map** = painted retail art, community art (bundled, credited), stitched client minimap tiles, or none. "
         "Positions marked ~ are approximate (database-derived).", "",
         "| Level | Dungeon | Map | Entrance | Bosses | Positions | Portraits | Loot |", "|---|---|---|---|---|---|---|---|"]
for lv, name, inst, a, nb, pos, ap, port, lt, en, lvs in rows:
    lines.append(f"| {lvs} | {name} ({inst}) | {a} | {'yes' if en else '**no**'} | {nb} | {pos}/{nb}{' (~%d)' % ap if ap else ''} | {port}/{nb} | {lt}/{nb} |")
tot = lambda i: sum(r[i] for r in rows)
lines += ["", f"Totals: {tot(4)} bosses; {tot(5)} with positions; {tot(7)} with portraits; {tot(8)} with loot.", "",
          "What still needs a human: map art for dungeons marked `none`, positions (`/dm edit`), portraits (`/dm display` or boss_display.csv), entrances (`data/manual/overrides.csv`). "
          "Everything else regenerates with `tools/update.py`."]
open(os.path.join(ROOT, "data/STATUS.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("\n".join(lines[5:5 + 3 + len(rows)]) if False else f"wrote data/STATUS.md ({len(rows)} dungeons)")
